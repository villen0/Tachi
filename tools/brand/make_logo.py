#!/usr/bin/env python3
"""Generates src/brand_logo.h: the Revsense wordmark ("Rev" white, "sense" red) as one alpha8 bitmap, cut out of the logo picture.
The ring, arc, needle and hub are drawn in code (src/brand.h) so they can animate; only the lowercase wordmark needs a bitmap
(the UI fonts are capitals only).
Usage: python3 make_logo.py revsense_logo.png ../../src/brand_logo.h        (needs Pillow and numpy)"""
import sys
import numpy as np
from PIL import Image

SCALE = 0.433            # logo pixels -> screen pixels (the ring of the logo is 624 px wide, 270 px on the screen)
SPLIT_X = 481            # column of the logo picture between "Rev" and "sense"
ROWS = (812, 912)        # rows that hold the wordmark

def main(png, out):
    src = np.array(Image.open(png).convert("RGB")).astype(float)
    bg = src[5, 5]
    reg = src[ROWS[0]:ROWS[1], 250:830]
    diff = np.abs(reg - bg).sum(axis=2)
    cols = np.where(diff.max(axis=0) > 80)[0]; rows = np.where(diff.max(axis=1) > 80)[0]
    x0, x1, y0, y1 = cols.min(), cols.max() + 1, rows.min(), rows.max() + 1
    crop = reg[y0:y1, x0:x1]
    split = SPLIT_X - 250 - x0
    white = np.array([255, 255, 255.]); red = np.array([231, 70, 42.])
    def alpha(c): v = c - bg; return np.clip(((crop - bg) @ v) / (v @ v), 0, 1)
    a = np.where(np.arange(crop.shape[1])[None, :] < split, alpha(white), alpha(red))
    w, h = int(round(a.shape[1] * SCALE)), int(round(a.shape[0] * SCALE))
    img = Image.fromarray((a * 255).astype(np.uint8)).resize((w, h), Image.LANCZOS)
    data = np.array(img).flatten()
    sx = int(round(split * SCALE))
    lines = ["#pragma once", "// Generated by tools/brand/make_logo.py from tools/brand/revsense_logo.png. Do not edit.",
             "#include <stdint.h>", "namespace brandlogo {",
             f"constexpr int WM_W = {w}, WM_H = {h}, WM_SPLIT = {sx};   // pixels left of WM_SPLIT are \"Rev\" (white), the rest \"sense\" (red)",
             "static const uint8_t WM_A[WM_W * WM_H] = {"]
    for i in range(0, len(data), 24): lines.append("  " + ",".join(str(int(v)) for v in data[i:i + 24]) + ",")
    lines += ["};", "}  // namespace brandlogo", ""]
    open(out, "w").write("\n".join(lines)); print("wordmark", w, "x", h, "split", sx, "bytes", len(data))

if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
