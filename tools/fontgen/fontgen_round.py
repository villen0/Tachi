#!/usr/bin/env python3
"""Generates src/round_font.h: Krona One glyph bitmaps in larger sizes for the round 480x480 dial pages (src/round_ui.h).
Reuses the renderer of fontgen.py. Usage: python3 fontgen_round.py KronaOne-Regular.ttf ../../src/round_font.h"""
import sys
from fontgen import fit_size, render

CLASSES = [  # name, chars, cap height px, stroke, gap px
    ("HUGE", "0123456789", 104, 0, 3),
    ("BIG", "0123456789.-", 56, 0, 2),
    ("MED", "0123456789.-%/", 28, 0, 2),
    ("LBL", "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789.:-%/+ ", 17, 0, 1),
]

def main(font, out):
    lines = ["#pragma once", "// Generated by tools/fontgen/fontgen_round.py from Krona One (SIL Open Font License). Do not edit.",
             "#include <stdint.h>", "namespace roundfont {", "struct Glyph { uint32_t off; uint8_t w, adv; };"]
    for name, chars, cap, stroke, gap in CLASSES:
        size = fit_size(font, cap)
        glyphs = {}
        for ch in chars:
            if ch == " ": glyphs[ch] = (None, max(2, cap // 2 + 1)); continue
            glyphs[ch] = (render(font, ch, size, cap, stroke), None)
        digit_w = max(g[0].width for c, g in glyphs.items() if c.isdigit())
        data = []; tab = []
        for ch in chars:
            im, adv = glyphs[ch]
            if im is None: tab.append((len(data), 0, adv)); continue
            off = len(data); data.extend(list(im.tobytes()))
            tab.append((off, im.width, (digit_w + gap) if ch.isdigit() else (im.width + gap)))
        lines.append(f"// {name}: cap height {cap} px, glyphs '{chars}'")
        lines.append(f"constexpr int {name}_H = {cap};")
        lines.append(f"static const char {name}_CHARS[] = \"{chars}\";")
        lines.append(f"static const Glyph {name}_G[] = {{" + ",".join(f"{{{o},{w},{a}}}" for o, w, a in tab) + "};")
        lines.append(f"static const uint8_t {name}_D[] = {{")
        row = []
        for v in data:
            row.append(str(v))
            if len(row) == 40: lines.append(",".join(row) + ","); row = []
        if row: lines.append(",".join(row))
        lines.append("};")
        print(name, "size", size, "glyphs", len(chars), "bytes", len(data))
    lines.append("}  // namespace roundfont")
    open(out, "w").write("\n".join(lines) + "\n")

if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
