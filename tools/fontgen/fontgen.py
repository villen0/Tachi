#!/usr/bin/env python3
"""Generates src/cluster_font.h: anti-aliased 8-bit alpha glyph bitmaps of Krona One (SIL OFL) in a few size classes.
Usage: python3 fontgen.py KronaOne-Regular.ttf ../../src/cluster_font.h
Each class: uniform cell height = digit cap height; digits share one advance (tabular), other glyphs are tight."""
import sys
from PIL import Image, ImageDraw, ImageFont

SS = 4  # supersampling
CLASSES = [  # name, chars, cap height px, stroke (in supersampled px), gap px
    ("GEAR", "N123456-", 50, 5, 0),
    ("BIG", "0123456789", 24, 3, 2),
    ("MED", "0123456789.:-%OK", 11, 1, 2),
    ("SML", "0123456789.:-%OK", 8, 0, 1),
    ("LBL", "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789.:-%/+ ", 6, 0, 1),
]

def fit_size(path, cap):
    lo, hi = 6, 400
    while lo < hi:
        mid = (lo + hi) // 2
        f = ImageFont.truetype(path, mid * SS)
        b = f.getbbox("0")
        if (b[3] - b[1]) >= cap * SS: hi = mid
        else: lo = mid + 1
    return lo

def render(path, ch, size, cap, stroke):
    f = ImageFont.truetype(path, size * SS)
    # digit cap box so every glyph shares the baseline
    zb = f.getbbox("0", stroke_width=stroke)
    top0, bot0 = zb[1], zb[3]
    H = cap * SS
    img = Image.new("L", (size * SS * 2, H + 8 * SS), 0)
    d = ImageDraw.Draw(img)
    d.text((SS * 2, -top0 + SS * 2 + (H - (bot0 - top0)) // 2), ch, font=f, fill=255, stroke_width=stroke, stroke_fill=255)
    bb = img.getbbox()
    if not bb: return None
    crop = img.crop((bb[0], SS * 2 - 0, bb[2], SS * 2 + H))   # keep full cell height
    small = crop.resize((max(1, round(crop.width / SS)), cap), Image.BOX)
    return small

def main(font, out):
    lines = ["#pragma once", "// Generated by tools/fontgen/fontgen.py from Krona One (SIL Open Font License). Do not edit.",
             "#include <stdint.h>", "namespace clusterfont {", "struct Glyph { uint16_t off; uint8_t w, adv; };"]
    for name, chars, cap, stroke, gap in CLASSES:
        size = fit_size(font, cap)
        glyphs = {}
        for ch in chars:
            if ch == " ": glyphs[ch] = (None, max(2, cap // 2 + 1)); continue
            im = render(font, ch, size, cap, stroke)
            glyphs[ch] = (im, None)
        digit_w = max(g[0].width for c, g in glyphs.items() if c.isdigit()) if any(c.isdigit() for c in chars) else 0
        data = []; tab = []
        for ch in chars:
            im, adv = glyphs[ch]
            if im is None: tab.append((len(data), 0, adv)); continue
            w = im.width; px = list(im.tobytes())
            off = len(data); data.extend(px)
            a = digit_w + gap if ch.isdigit() else w + gap
            tab.append((off, w, a))
        lines.append(f"// {name}: cap height {cap} px, glyphs '{chars}'")
        lines.append(f"constexpr int {name}_H = {cap};")
        lines.append(f"static const char {name}_CHARS[] = \"{chars}\";")
        lines.append(f"static const Glyph {name}_G[] = {{" + ",".join(f"{{{o},{w},{a}}}" for o, w, a in tab) + "};")
        lines.append(f"static const uint8_t {name}_D[] = {{")
        row = []
        for i, v in enumerate(data):
            row.append(str(v))
            if len(row) == 40: lines.append(",".join(row) + ","); row = []
        if row: lines.append(",".join(row))
        lines.append("};")
        print(name, "size", size, "glyphs", len(chars), "bytes", len(data))
    lines.append("}  // namespace clusterfont")
    open(out, "w").write("\n".join(lines) + "\n")

if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
